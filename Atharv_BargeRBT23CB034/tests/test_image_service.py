"""
Unit tests for services/image_service.py.
Tests image validation, format checks, corrupted image handling,
transparency handling, resizing, and size limit enforcement.
"""

import io
import pytest
from PIL import Image

from services.image_service import (
    process_uploaded_image,
    validate_file_size,
    validate_image_format,
    convert_to_rgb,
    resize_image_if_needed,
    image_to_bytes,
    ImageValidationError,
    MAX_FILE_SIZE_BYTES,
)


def create_test_image(format: str = "JPEG", size=(300, 200), mode: str = "RGB", color=(100, 150, 200)) -> bytes:
    """Helper to generate in-memory image bytes."""
    buf = io.BytesIO()
    img = Image.new(mode, size, color)
    if format.upper() == "PNG" and mode == "RGBA":
        # Draw some transparent pixels
        img.putpixel((10, 10), (0, 0, 0, 0))
    img.save(buf, format=format)
    return buf.getvalue()


def test_valid_jpeg_upload():
    """Test 1: Valid JPEG image upload and processing."""
    jpeg_bytes = create_test_image(format="JPEG", size=(400, 300))
    img, meta = process_uploaded_image(jpeg_bytes)
    
    assert isinstance(img, Image.Image)
    assert meta["format"] == "JPEG"
    assert meta["current_width"] == 400
    assert meta["current_height"] == 300
    assert meta["mode"] == "RGB"
    assert not meta["was_resized"]


def test_valid_png_upload_with_transparency():
    """Test 2: Valid PNG image upload with transparency handling."""
    png_bytes = create_test_image(format="PNG", size=(250, 250), mode="RGBA", color=(255, 0, 0, 128))
    img, meta = process_uploaded_image(png_bytes)
    
    assert isinstance(img, Image.Image)
    assert meta["format"] == "PNG"
    assert img.mode == "RGB"  # Must be converted to RGB without alpha
    assert meta["mode"] == "RGB"


def test_valid_webp_upload():
    """Test: Valid WEBP image upload."""
    webp_bytes = create_test_image(format="WEBP", size=(350, 250))
    img, meta = process_uploaded_image(webp_bytes)
    
    assert isinstance(img, Image.Image)
    assert meta["format"] == "WEBP"
    assert img.mode == "RGB"


def test_unsupported_file_rejection():
    """Test 3: Unsupported format rejection (e.g. BMP)."""
    buf = io.BytesIO()
    bmp_img = Image.new("RGB", (100, 100), color="blue")
    bmp_img.save(buf, format="BMP")
    
    with pytest.raises(ImageValidationError) as exc_info:
        process_uploaded_image(buf.getvalue())
    assert "Unsupported image format" in str(exc_info.value)


def test_corrupted_image_rejection():
    """Test 4: Corrupted bytes rejection."""
    garbage_bytes = b"NOT_AN_IMAGE_RANDOM_CORRUPT_BYTES_XYZ"
    
    with pytest.raises(ImageValidationError) as exc_info:
        process_uploaded_image(garbage_bytes)
    assert "Invalid or corrupted image" in str(exc_info.value) or "Could not open" in str(exc_info.value)


def test_oversized_image_rejection():
    """Test 5: Oversized file rejection (> 10 MB)."""
    fake_oversized_bytes = b"0" * (MAX_FILE_SIZE_BYTES + 1024)
    
    with pytest.raises(ImageValidationError) as exc_info:
        validate_file_size(fake_oversized_bytes)
    assert "File size exceeds" in str(exc_info.value)


def test_empty_file_rejection():
    """Test: Empty file rejection."""
    with pytest.raises(ImageValidationError) as exc_info:
        validate_file_size(b"")
    assert "empty" in str(exc_info.value).lower()


def test_large_image_proportional_resizing():
    """Test: Images exceeding 1600px are downsampled preserving aspect ratio."""
    large_bytes = create_test_image(format="JPEG", size=(3200, 1600))
    img, meta = process_uploaded_image(large_bytes)
    
    assert meta["was_resized"] is True
    assert img.size[0] == 1600
    assert img.size[1] == 800  # 2:1 aspect ratio strictly preserved


def test_image_to_bytes():
    """Test: In-memory byte conversion."""
    test_img = Image.new("RGB", (50, 50), color="green")
    output_bytes = image_to_bytes(test_img, format="JPEG")
    assert len(output_bytes) > 0
    # Re-verify the generated bytes
    reloaded = Image.open(io.BytesIO(output_bytes))
    assert reloaded.format == "JPEG"
